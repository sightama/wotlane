#!/usr/bin/env python3
"""Turns the RCDATA resources of native/wotm.rc into a C++ header of byte arrays, for builds without Windows resources.

On Windows the executable carries native/wotm.rc (read with FindResourceA). macOS and Linux have no .rc, so
tools/build_runtime.sh runs this script and native/wotm_embedded.hpp includes the result (wotm_resources.gen.h, in
<build>/wotm_gen). Only RCDATA lines are read (`NAME RCDATA "relative/path"`); the ICON entry is Windows-only.

Usage: python3 tools/embed_resources.py <native/wotm.rc> <output header>
The header is rewritten only when its content changes, so ninja doesn't recompile what includes it.
"""
import re
import sys
from pathlib import Path

LINE = re.compile(r'^\s*(\w+)\s+RCDATA\s+"([^"]+)"')


def main():
    if len(sys.argv) == 2 and sys.argv[1] in ("-h", "--help"):
        print(__doc__.strip())
        return 0
    if len(sys.argv) != 3:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    rc, out = Path(sys.argv[1]), Path(sys.argv[2])
    entries = [m.groups() for m in map(LINE.match, rc.read_text(encoding="utf-8").splitlines()) if m]
    if not entries:
        print(f"error: no RCDATA lines in {rc}", file=sys.stderr)
        return 1
    parts = [f"// Generated by tools/embed_resources.py from {rc.name}: do not edit.", "#pragma once",
             "#define WOTM_HAVE_EMBEDDED_RESOURCES 1", "namespace wotm_embedded", "{"]
    for name, rel in entries:
        path = rc.parent / rel
        if not path.is_file():
            print(f"error: {rc.name}: {name} points to missing file {path}", file=sys.stderr)
            return 1
        data = path.read_bytes()
        rows = (",".join(str(b) for b in data[i:i + 32]) for i in range(0, len(data), 32))
        parts.append(f"inline constexpr unsigned char k{name}[] = {{")
        parts.append(",\n".join(rows))
        parts.append("};")
    parts.append("struct Resource\n{\n    const char *name;\n    const unsigned char *data;\n    int size;\n};")
    table = ", ".join(f'{{"{n}", k{n}, static_cast<int>(sizeof k{n})}}' for n, _ in entries)
    parts.append(f"inline constexpr Resource kResources[] = {{{table}}};")
    parts.append("} // namespace wotm_embedded\n")
    text = "\n".join(parts)
    if not out.exists() or out.read_text(encoding="utf-8") != text:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
