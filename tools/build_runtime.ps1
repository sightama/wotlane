# Called by build_runtime.bat: runs the runtime build and shows a progress bar.
# Ninja reports only a few steps ([1/4] compiles ps2_runtime.cpp, which takes almost all the time), so the bar
# combines the steps in the log with the duration of the last build (saved in <runtime>\.wotm_build_secs_<bat>).
# Usage: build_runtime.ps1 <runtime folder> <bat> <log>
param([string]$Dir, [string]$Bat, [string]$Log)

$ErrorActionPreference = 'Stop'
$logPath  = Join-Path $Dir $Log
New-Item -ItemType Directory -Force (Split-Path $logPath -Parent) | Out-Null   # the runtime's logs\: the .bat writes there
$timeFile = Join-Path $Dir (".wotm_build_secs_" + [IO.Path]::GetFileNameWithoutExtension($Bat))

$expected = if ($Bat -eq 'build.bat') { 300.0 } else { 90.0 }
try { if (Test-Path $timeFile) { $expected = [double](Get-Content $timeFile -TotalCount 1) } } catch {}
if ($expected -lt 5) { $expected = 5 }

# "Guinea pig" runtime (build_runtime.bat nm): same runtime and hooks, but the translated game comes from <repo>\recomp\nm (ELF with the
# rewritten functions; sh tools/wsl/recomp_nm.sh). Configures build_dev_nm from configure_dev.bat and creates build_dev_nm.bat the first time.
if ($Bat -eq 'build_dev_nm.bat') {
    $repo = Split-Path $PSScriptRoot -Parent
    $nmDir = Join-Path $repo 'recomp\nm'
    if (-not (Test-Path (Join-Path $nmDir 'register_functions.cpp'))) { throw "recomp\nm does not exist: in WSL, run sh tools/wsl/recomp_nm.sh" }
    $nmCmake = ($nmDir -replace '\\', '/')
    if (-not (Test-Path "$Dir\build_dev_nm\build.ninja")) {
        $cfg = Get-Content "$Dir\configure_dev.bat" -Raw
        $cfg = $cfg -replace 'build_dev"', "build_dev_nm`" -DPS2X_RUNNER_DIR=$nmCmake"
        Set-Content "$Dir\configure_dev_nm.bat" $cfg -NoNewline
        Write-Host "configuring build_dev_nm (translated game from $nmDir)..."
        & $env:ComSpec /c "`"$Dir\configure_dev_nm.bat`"" | Select-Object -Last 3
        if (-not (Test-Path "$Dir\build_dev_nm\build.ninja")) { throw "configure_dev_nm.bat failed" }
    }
    if (-not (Test-Path "$Dir\$Bat")) {
        (Get-Content "$Dir\build_dev.bat" -Raw) -replace 'build_dev', 'build_dev_nm' | Set-Content "$Dir\$Bat" -NoNewline
    }
}
(Get-Item "$Dir\PS2Recomp\ps2xRuntime\src\lib\ps2_runtime.cpp").LastWriteTime = Get-Date
# VU0 microprograms as C++ (generated from the ELF; without the .inc the runtime only uses the interpreter). They go to <build>\wotm_gen,
# which the runtime's CMake puts on the include path (it is game code: outside the repo and outside the PS2Recomp tree)
$gen = Join-Path $PSScriptRoot 'vu0native.py'
$genDir = Join-Path $Dir ([IO.Path]::GetFileNameWithoutExtension($Bat)) | Join-Path -ChildPath 'wotm_gen'
New-Item -ItemType Directory -Force $genDir | Out-Null
# guinea pig: native-layer hooks and reads use the addresses of the nmall ELF (generated by recomp_nm.sh; native/wotm_syms.h uses it
# when it is on the include path, and only build_dev_nm's wotm_gen has it)
if ($Bat -eq 'build_dev_nm.bat') {
    $nmSyms = Join-Path $repo 'recomp\nm\wotm_syms_nm.h'
    if (-not (Test-Path $nmSyms)) { throw "$nmSyms is missing (rerun sh tools/wsl/recomp_nm.sh)" }
    Copy-Item $nmSyms $genDir -Force
}
$inc = Join-Path $genDir 'wotm_vu0_native.gen.inc'
$elf = Join-Path $PSScriptRoot '..\disc\SCUS_971.97'
if ((Test-Path $elf) -and (-not (Test-Path $inc) -or (Get-Item $inc).LastWriteTime -lt (Get-Item $gen).LastWriteTime)) {
    & python $gen $elf $inc | Out-Null
    if ($LASTEXITCODE -ne 0) { Write-Host 'vu0native.py failed: VU0 stays on the interpreter' -ForegroundColor Yellow }
}
# (main.cpp used to sit in a unity-build batch with the translated game and ninja didn't recompile it; since 2026-10-19 the translated
# game is the ps2_game_code object library and main.cpp compiles on its own into each executable, ps2EntryRunner and wotm)
if (Test-Path $logPath) { Remove-Item $logPath -Force }

# the .bat's own output (vcvars etc.) goes to a file so it doesn't break the bar's line; it is shown only on failure
$outFile = Join-Path $env:TEMP 'wotm_build_runtime.out'
$errFile = Join-Path $env:TEMP 'wotm_build_runtime.err'
$proc = Start-Process -FilePath $env:ComSpec -ArgumentList "/c `"`"$Dir\$Bat`"`"" -NoNewWindow -PassThru `
    -RedirectStandardOutput $outFile -RedirectStandardError $errFile
$null = $proc.Handle  # without grabbing the handle early, ExitCode comes back empty on PS 5.1
$sw = [Diagnostics.Stopwatch]::StartNew()
$full = [char]0x2588; $empty = [char]0x2591

function Read-Log {
    # cmake is still writing: open with sharing so we don't fight over the file
    try {
        $fs = [IO.File]::Open($logPath, 'Open', 'Read', 'ReadWrite')
        try { return (New-Object IO.StreamReader($fs)).ReadToEnd() } finally { $fs.Dispose() }
    } catch { return '' }
}

function Fmt([double]$s) { '{0}:{1:00}' -f [int][math]::Floor($s / 60), [int]($s % 60) }

function Draw([double]$frac, [string]$what) {
    $width = 30
    $n = [int][math]::Floor($frac * $width)
    $bar = ([string]$full * $n) + ([string]$empty * ($width - $n))
    $t = $sw.Elapsed.TotalSeconds
    $line = '  {0} {1,3}%  {2} / ~{3}  {4}' -f $bar, [int]($frac * 100), (Fmt $t), (Fmt ([math]::Max($expected, $t))), $what
    $max = 79
    try { $max = [Console]::WindowWidth - 1 } catch {}
    if ($line.Length -gt $max) { $line = $line.Substring(0, $max) }
    [Console]::Write("`r" + $line.PadRight($max))
}

$frac = 0.0; $what = 'preparing...'
while (-not $proc.HasExited) {
    $steps = [regex]::Matches((Read-Log), '(?m)^\[(\d+)/(\d+)\]\s*(.*)$')
    if ($steps.Count -gt 0) {
        $m = $steps[$steps.Count - 1]
        $done = [int]$m.Groups[1].Value; $total = [int]$m.Groups[2].Value
        $what = '[' + $done + '/' + $total + '] ' + ($m.Groups[3].Value -replace '^(Building|Linking) CXX (object|static library|executable) ', '')
        $what = $what -replace '^(\[\d+/\d+\] ).*[\\/]', '$1'
        # ninja only writes "[1/4] ... ps2_runtime.cpp.obj" when that compile finishes
        if ($done -eq 0) { $what = 'compiling ps2_runtime.cpp' }
        $floor = if ($total -gt 0 -and $what -match 'ps2EntryRunner|wotm.exe') { 0.95 } elseif ($total -gt 0 -and $what -match '\.lib') { 0.9 } else { 0 }
    } else { $floor = 0 }
    # time vs. the last build, never reaching 100% before it finishes
    $t = [math]::Min($sw.Elapsed.TotalSeconds / $expected, 0.99)
    $frac = [math]::Max([math]::Max($frac, $t), $floor)
    Draw $frac $what
    Start-Sleep -Milliseconds 250
}
$proc.WaitForExit()
$rc = $proc.ExitCode
# build_dev.bat doesn't pass on ninja's failure (it exits 0 and the old .exe stays): check the log too
if ($rc -eq 0 -and (Read-Log) -match '(?m)^FAILED:|error C\d{4}|error LNK\d{4}') { $rc = 1 }
$secs = $sw.Elapsed.TotalSeconds

if ($rc -eq 0) {
    Draw 1.0 'done'
    [Console]::WriteLine()
    try { Set-Content -Path $timeFile -Value ([int][math]::Ceiling($secs)) -Encoding ascii } catch {}
    # build identity for online matches (wotm.buildid next to the exe; every PC in a match needs the same one)
    $buildName = [IO.Path]::GetFileNameWithoutExtension($Bat)
    $bid = & python (Join-Path $PSScriptRoot 'build_id.py') --runtime $Dir --build $buildName --write
    if ($LASTEXITCODE -eq 0) { Write-Host "build $bid" } else { Write-Host 'build_id.py failed: no wotm.buildid (online matches will reject this build)' -ForegroundColor Yellow }
} else {
    Draw $frac 'FAILED'
    [Console]::WriteLine()
    foreach ($f in $outFile, $errFile) { if (Test-Path $f) { Get-Content $f | Where-Object { $_ -ne '' } } }
    # show the compiler/linker errors instead of just the last line
    $errs = (Read-Log) -split "`r?`n" | Where-Object { $_ -match 'error|FAILED' } | Select-Object -First 20
    $errs | ForEach-Object { Write-Host $_ -ForegroundColor Red }
}
exit $rc
